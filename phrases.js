// Phrase library — aalap phrases and taans to learn by ear. Edit freely; the Library view builds
// itself from this file. Same swara notation as ragas.js (S r R g G m M P d D n N, N. = mandra,
// S' = taar), plus rhythm:
//
//   notes: beats separated by spaces; the notes inside one beat share it equally.
//     "S"          one note on the beat           "N.RGM"   four notes in one beat (chaugun)
//     "G -"        G held for two beats           "R-S-"    R, hold, S, hold: two notes per beat
//     -            hold the previous note for that slot (a whole beat, or part of one)
//     _            silence for that slot
//     ~            glide (meend) into the next note: "~G" or "M~G"
//     ~~           slow meend: most of the note is the slide: "~~G"
//     ^            andolan: a slow swing on the note: "^g"
//     ?            your turn: shown and timed but not played: "?G" (used by Practice)
//     (x)          kan: a quick touch of x before the next note: "(G)R"
//     |            vibhag line, only for reading (ignored)
//
//   raga     name exactly as in ragas.js
//   kind     aalap | sapaat | vakra | gamak | chhut | tihai   (see KINDS)
//   name     a short handle
//   lands    'sam': the last beat falls on sam (playback starts the phrase so it does).
//            Otherwise the first beat falls on sam.
//   gamak    true: every note is shaken (approached from the note above), as in a gamak taan
//   bpm      a tempo to start learning it at (you change the tempo in the Library)
//   level    1 = start here, 2 = once that's clean, 3 = advanced
//   why      what makes it work, in a line or two
//   src      'written' = composed in the Kirana style for this app, not transcribed
//            (ref: the writing it follows, if any);
//            'notation' = the notes come from a written source: from = who wrote it, url = where,
//            srcNote = what this app added (the rhythm, always; octaves the source left unmarked);
//            otherwise the recording and time it was transcribed from
//   check    true = worth checking with a teacher (everything written, not transcribed, is)
//
// Phrases marked src: 'notation' follow notations by raga writers (Rajan Parrikar, Ragajunglism,
// David Clarke); no full text notation of Bhimsen Joshi's own aalaps or taans was found, and only one
// short phrase of his (Puriya Dhanashree) is notated from a recording.
//
// The aalaps of each raga are a badhat: each one adds a little more of the raga, from mandra Sa
// up to the taar saptak, the way a Kirana-style vilambit unfolds. Sing them in akaar.

